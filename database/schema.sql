create or replace function public.create_public_order(
  input_customer_name text,
  input_customer_phone text,
  input_table_number integer,
  input_order_type text,
  input_notes text,
  input_items jsonb,
  input_delivery_zone_id text default null,
  input_delivery_address text default null,
  input_delivery_reference text default null,
  input_payment_method text default null,
  input_change_for integer default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  new_order public.orders;
  item jsonb;
  product_row public.products;
  zone_row public.delivery_zones;
  settings_row public.restaurant_settings;
  order_subtotal integer := 0;
  order_fee integer := 0;
begin
  if input_order_type not in ('table', 'takeaway', 'delivery') then
    raise exception 'Tipo de pedido inválido.';
  end if;

  if jsonb_typeof(input_items) <> 'array' or jsonb_array_length(input_items) = 0 then
    raise exception 'El pedido no tiene productos.';
  end if;

  select * into settings_row from public.restaurant_settings where id = 1;

  if input_order_type = 'table' and input_table_number is null then
    raise exception 'Selecciona una mesa.';
  end if;

  if input_order_type <> 'table'
     and (nullif(trim(input_customer_name), '') is null or nullif(trim(input_customer_phone), '') is null) then
    raise exception 'Nombre y teléfono son obligatorios para este tipo de pedido.';
  end if;

  -- Los precios y el costo de envío se calculan siempre desde la base de datos,
  -- nunca desde el payload del cliente.
  for item in select * from jsonb_array_elements(input_items)
  loop
    select *
    into product_row
    from public.products
    where id = (item ->> 'product_id')::uuid
      and available = true;

    if product_row.id is null then
      raise exception 'Uno de los productos no está disponible.';
    end if;

    order_subtotal := order_subtotal + product_row.price * greatest((item ->> 'quantity')::integer, 1);
  end loop;

  if input_order_type = 'delivery' then
    if not coalesce(settings_row.delivery_enabled, true) then
      raise exception 'Los domicilios están desactivados en este momento.';
    end if;

    select * into zone_row
    from public.delivery_zones
    where id = input_delivery_zone_id and active = true;

    if zone_row.id is null then
      raise exception 'Selecciona una zona de entrega válida.';
    end if;

    if length(coalesce(trim(input_delivery_address), '')) < 8 then
      raise exception 'Escribe una dirección de entrega completa.';
    end if;

    if order_subtotal < coalesce(settings_row.delivery_min_order, 0) then
      raise exception 'El pedido no alcanza el mínimo para domicilio.';
    end if;

    order_fee := zone_row.fee;
  end if;

  insert into public.orders (
    customer_name,
    customer_phone,
    table_number,
    order_type,
    notes,
    subtotal,
    delivery_fee,
    delivery_address,
    delivery_zone_id,
    delivery_zone_name,
    delivery_reference,
    delivery_eta_minutes,
    payment_method,
    change_for,
    total,
    status
  )
  values (
    nullif(trim(input_customer_name), ''),
    nullif(trim(input_customer_phone), ''),
    case when input_order_type = 'table' then input_table_number else null end,
    input_order_type,
    nullif(trim(input_notes), ''),
    order_subtotal,
    order_fee,
    case when input_order_type = 'delivery' then trim(input_delivery_address) else null end,
    case when input_order_type = 'delivery' then zone_row.id else null end,
    case when input_order_type = 'delivery' then zone_row.name else null end,
    case when input_order_type = 'delivery' then nullif(trim(input_delivery_reference), '') else null end,
    case when input_order_type = 'delivery' then zone_row.eta_minutes else null end,
    case when input_order_type = 'delivery' then coalesce(input_payment_method, 'cash') else null end,
    case when input_order_type = 'delivery' and input_payment_method = 'cash' then input_change_for else null end,
    order_subtotal + order_fee,
    'pending'
  )
  returning * into new_order;

  for item in select * from jsonb_array_elements(input_items)
  loop
    select * into product_row
    from public.products
    where id = (item ->> 'product_id')::uuid;

    insert into public.order_items (order_id, product_id, name, quantity, unit_price, subtotal)
    values (
      new_order.id,
      product_row.id,
      product_row.name,
      greatest((item ->> 'quantity')::integer, 1),
      product_row.price,
      product_row.price * greatest((item ->> 'quantity')::integer, 1)
    );
  end loop;

  return jsonb_build_object(
    'id', new_order.id,
    'number', new_order.number,
    'lookup_token', new_order.lookup_token,
    'status', new_order.status,
    'subtotal', new_order.subtotal,
    'delivery_fee', new_order.delivery_fee,
    'total', new_order.total
  );
end;
$$;

create or replace function public.get_public_order(
  input_number bigint,
  input_lookup_token uuid
)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id', o.id,
    'number', o.number,
    'customer_name', o.customer_name,
    'customer_phone', o.customer_phone,
    'table_number', o.table_number,
    'order_type', o.order_type,
    'notes', o.notes,
    'subtotal', o.subtotal,
    'delivery_fee', o.delivery_fee,
    'total', o.total,
    'status', o.status,
    'created_at', o.created_at,
    'delivery', case
      when o.order_type = 'delivery' then jsonb_build_object(
        'address', o.delivery_address,
        'zone_id', o.delivery_zone_id,
        'zone_name', o.delivery_zone_name,
        'reference', o.delivery_reference,
        'eta_minutes', o.delivery_eta_minutes
      )
      else null
    end,
    'payment', case
      when o.payment_method is null then null
      else jsonb_build_object('method', o.payment_method, 'change_for', o.change_for)
    end,
    'status_history', coalesce(
      (
        select jsonb_agg(jsonb_build_object('status', h.status, 'at', h.changed_at) order by h.changed_at)
        from public.order_status_history h
        where h.order_id = o.id
      ),
      '[]'::jsonb
    ),
    'items', coalesce(
      jsonb_agg(
        jsonb_build_object(
          'name', coalesce(oi.name, p.name, 'Producto eliminado'),
          'quantity', oi.quantity,
          'unit_price', oi.unit_price,
          'subtotal', oi.subtotal
        )
      ) filter (where oi.id is not null),
      '[]'::jsonb
    )
  )
  from public.orders o
  left join public.order_items oi on oi.order_id = o.id
  left join public.products p on p.id = oi.product_id
  where o.number = input_number
    and o.lookup_token = input_lookup_token
  group by o.id;
$$;

-- Habilita eventos en vivo (Realtime) para que el panel admin y el sitio
-- publico reciban cambios sin necesidad de recargar la pagina.
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'orders') then
    alter publication supabase_realtime add table public.orders;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'order_items') then
    alter publication supabase_realtime add table public.order_items;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'products') then
    alter publication supabase_realtime add table public.products;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'tables') then
    alter publication supabase_realtime add table public.tables;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'restaurant_settings') then
    alter publication supabase_realtime add table public.restaurant_settings;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'delivery_zones') then
    alter publication supabase_realtime add table public.delivery_zones;
  end if;
end $$;

