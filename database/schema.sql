-- security definer: el INSERT en order_status_history debe pasar aunque
-- quien actualice el pedido no tenga permiso directo de escritura en esa
-- tabla (solo hay política de lectura para admins).
create or replace function public.record_order_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.order_status_history (order_id, status)
    values (new.id, new.status);
  end if;

  -- Un pedido en mesa libera la mesa al cerrarse y la ocupa mientras está vivo.
  if new.table_number is not null then
    update public.tables
    set status = case
      when new.status in ('pending', 'preparing', 'ready', 'on_the_way') then 'occupied'
      else 'free'
    end
    where number = new.table_number;
  end if;

  return new;
end;
$$;

drop trigger if exists orders_record_status on public.orders;
create trigger orders_record_status
after insert or update of status on public.orders
for each row execute function public.record_order_status();

